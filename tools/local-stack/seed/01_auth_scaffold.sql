-- Supabase-compatible `auth` schema for the LOCAL database.
--
-- pg_dump of a Supabase project does not carry the auth schema (it is owned
-- by Supabase, not by the user), but the restored public schema references
-- `auth.uid()` in 119 RLS policies and in ~30 function bodies, so the local
-- copy needs an equivalent.  This mirrors the shape Supabase itself uses:
-- auth.users / auth.identities / auth.instances / auth.roles plus the
-- auth.uid() / auth.role() / auth.email() / auth.jwt() helpers.
--
-- The user rows are seeded separately (02_seed_auth_users.py) from the
-- restored public.profiles table, with a locally generated bcrypt hash — no
-- credential hash is copied from production.

create schema if not exists auth;

-- ---------------------------------------------------------------- instances
create table if not exists auth.instances (
    id uuid primary key default gen_random_uuid(),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);
insert into auth.instances (id)
values ('00000000-0000-0000-0000-000000000000')
on conflict (id) do nothing;

-- ---------------------------------------------------------------- users
create table if not exists auth.users (
    instance_id uuid,
    id uuid primary key default gen_random_uuid(),
    aud varchar(255),
    role varchar(255),
    email varchar(255),
    encrypted_password varchar(255),
    email_confirmed_at timestamptz,
    invited_at timestamptz,
    confirmation_token varchar(255),
    confirmation_sent_at timestamptz,
    recovery_token varchar(255),
    recovery_sent_at timestamptz,
    email_change_token_new varchar(255),
    email_change varchar(255),
    email_change_sent_at timestamptz,
    last_sign_in_at timestamptz,
    raw_app_meta_data jsonb,
    raw_user_meta_data jsonb,
    is_super_admin boolean,
    created_at timestamptz,
    updated_at timestamptz,
    phone_change text default '',
    phone_change_token varchar(255) default '',
    phone_change_sent_at timestamptz,
    email_change_token_current varchar(255) default '',
    email_change_confirm_status smallint default 0,
    phone_change_confirm_status smallint default 0,
    reauthentication_token varchar(255) default '',
    reauthentication_sent_at timestamptz,
    is_sso_user boolean not null default false,
    is_anonymous boolean not null default false
);
create index if not exists users_email_partial_key on auth.users (email varchar_pattern_ops);

-- ---------------------------------------------------------------- identities
create table if not exists auth.identities (
    id uuid primary key default gen_random_uuid(),
    user_id uuid not null references auth.users (id) on delete cascade,
    provider_id text not null,
    identity_data jsonb not null,
    provider text not null,
    last_sign_in_at timestamptz,
    created_at timestamptz,
    updated_at timestamptz,
    email text
);
create unique index if not exists identities_provider_id_provider_unique
    on auth.identities (provider_id, provider);

-- ---------------------------------------------------------------- roles
create table if not exists auth.roles (
    id int generated by default as identity primary key,
    name text not null unique,
    description text
);
insert into auth.roles (name, description) values
    ('anon', 'Anonymous role'),
    ('authenticated', 'Authenticated role'),
    ('service_role', 'Service role'),
    ('authenticator', 'Authenticator role'),
    ('supabase_auth_admin', 'Supabase Auth admin'),
    ('supabase_storage_admin', 'Supabase Storage admin')
on conflict (name) do nothing;

-- ---------------------------------------------------------------- helpers
-- auth.uid() mirrors Supabase's: it reads the request JWT claims that
-- PostgREST (here: the local API shim) puts on the connection.
create or replace function auth.uid()
returns uuid
language sql
stable
as $$
    select coalesce(
        nullif(current_setting('request.jwt.claim.sub', true), ''),
        (nullif(current_setting('request.jwt.claims', true), '')::jsonb ->> 'sub')
    )::uuid
$$;

create or replace function auth.role()
returns text
language sql
stable
as $$
    select coalesce(
        nullif(current_setting('request.jwt.claim.role', true), ''),
        (nullif(current_setting('request.jwt.claims', true), '')::jsonb ->> 'role'),
        'anon'
    )
$$;

create or replace function auth.email()
returns text
language sql
stable
as $$
    select coalesce(
        nullif(current_setting('request.jwt.claim.email', true), ''),
        (nullif(current_setting('request.jwt.claims', true), '')::jsonb ->> 'email')
    )
$$;

create or replace function auth.jwt()
returns jsonb
language sql
stable
as $$
    select coalesce(
        nullif(current_setting('request.jwt.claims', true), '')::jsonb,
        '{}'::jsonb
    )
$$;

grant usage on schema auth to anon, authenticated, service_role;
grant select on all tables in schema auth to authenticated, service_role;
grant all on all tables in schema auth to service_role;
grant execute on all functions in schema auth to anon, authenticated, service_role;
